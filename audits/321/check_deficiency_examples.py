"""Audit 321, part 3: sanity tests of the reformulated Corollary 2.4.

Via the twisted Euler characteristic, Corollary 2.4 (02-tower.tex l.230-236)
is equivalent to: for every finite presentation <n gens | m rels> of a group
with a torsion element g and a character rho with rho(g) != 1, the Fox matrix
at rho has rank <= m-1 (i.e. H_2 != 0), equivalently def(G) <= h_1(G;C_rho).
We test this on standard groups with torsion where deficiency is known, and
record the paper's group as the case where the bound would be new.

Run:  uv run --with sympy python check_deficiency_examples.py
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sympy as sp
from fox import gen, mul, inv, power, comm, fox_matrix, scalar_rep

z3 = sp.exp(2 * sp.pi * sp.I / 3)
lam = sp.symbols("lambda")

def report(name, relators, ngens, images, torsion_note):
    rep = scalar_rep(images)
    M = sp.Matrix(fox_matrix(relators, ngens, rep)).applyfunc(sp.simplify)
    m = len(relators)
    rk = M.rank(simplify=True)
    h2 = m - rk
    chi = 1 - ngens + m
    h1 = h2 - chi           # h0 = 0 since rho nontrivial
    deficiency = ngens - m
    verdict = "consistent" if h2 >= 1 else "VIOLATION of Cor 2.4"
    print(f"{name:34s} def={deficiency:2d} h2(Y;rho)={h2} h1(G;rho)={h1}  [{torsion_note}] -> {verdict}")
    return h2 >= 1

x, a, s = gen(0), gen(1), gen(2)   # generator indices 0,1,2
allok = True
# Z/2 * Z = <x, a | x^2>   (a plays the role of the free generator)
allok &= report("Z/2 * Z", [power(x, 2)], 2, [-1, lam], "x order 2, rho(x)=-1")
# Z/2 x Z = <x, a | x^2, [x,a]>
allok &= report("Z/2 x Z", [power(x, 2), comm(x, a)], 2, [-1, lam], "x order 2")
# one-relator with torsion <x,a | w^2>, w = x a x^-1 a^2 ; rho(x)=1, rho(a)=-1 gives rho(w) = -1
w = mul(x, a, inv(x), power(a, 2))
allok &= report("one-relator <x,a|w^2>", [power(w, 2)], 2, [1, -1], "w order 2, rho(w)=-1")
# A*Z with A = Z/15 x| Z/2 = <x,a | x a x^-1 a^-4, x^2>, free generator s
A_rels = [mul(x, a, inv(x), power(a, -4)), power(x, 2)]
allok &= report("(Z/15 x| Z/2) * Z", A_rels, 3, [-1, z3, lam], "x order 2")
# Z/2 * Z/2 * Z, rho nontrivial on first factor only
allok &= report("Z/2 * Z/2 * Z", [power(x, 2), power(a, 2)], 3, [-1, 1, lam], "x order 2")
# HNN of A over Z/3 with identity gluing: <x,a,s | A-rels, s a^5 s^-1 a^-5>; H_2 = Z/3, def<=0 by Epstein
allok &= report("A *_{Z/3} (identity HNN)", A_rels + [mul(s, power(a, 5), inv(s), power(a, -5))], 3, [-1, z3, lam], "a^5 order 3, rho=zeta^2")
# Z/6 vertex example: <a,b,s | a^6, a^3 b^-3, s a^2 s^-1 b^-2> (b^6 redundant): cycle-type graph of groups,
# H_2 = 0, b_1 = 1; rho(a)=rho(b)=-zeta (primitive 6th root), nontrivial on both edge groups
b = gen(1); a6 = gen(0); s3 = gen(2)
w6 = -z3
allok &= report("Z/6 *_{Z/2} Z/6 *_{Z/3} (3 rels)", [power(a6, 6), mul(power(a6, 3), power(b, -3)), mul(s3, power(a6, 2), inv(s3), power(b, -2))], 3, [w6, w6, lam], "a^3 order 2, rho=-1")

print()
print("Paper's group G (6 relators, 04-construction.tex l.14-27):")
x1, a1, x2, a2, s5 = (gen(i) for i in range(5))
R = [mul(x1, a1, inv(x1), power(a1, -4)), mul(x2, a2, inv(x2), power(a2, -3)),
     mul(x1, power(a2, -13)), mul(s5, x2, inv(s5), power(a1, -5)), power(x1, 2), power(x2, 3)]
allok &= report("G = P/K (6-relator presentation)", R, 5, [-1, z3, z3**2, -1, 1], "x1 order 2, rho=-1")
print("Cor 2.4 + h1(G;rho)=0 would force every finite 2-complex Y with pi_1=G to have chi(Y)>=1,")
print("i.e. def(G) <= 0, whereas the 5-generator relation module is generated by r1..r4 (K_ab=0):")
print("a relation gap  d_F(N) >= 5 > 4 >= d_G(N_ab)  -- not stated in the paper.")
print("\nALL CONSISTENT" if allok else "\nINCONSISTENCY FOUND")
