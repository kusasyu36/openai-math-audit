class SemiDirect:
    """Z/n x| Z/m with generator x acting a -> a^k.  Elements (i, j) = a^i x^j."""
    def __init__(self, n, m, k):
        assert pow(k, m, n) == 1, "action must have order dividing m"
        self.n, self.m, self.k = n, m, k
    def mul(self, g, h):
        (i1, j1), (i2, j2) = g, h
        # a^i1 x^j1 a^i2 x^j2 = a^{i1 + k^j1 i2} x^{j1+j2}
        return ((i1 + pow(self.k, j1, self.n) * i2) % self.n, (j1 + j2) % self.m)
    def inv(self, g):
        i, j = g
        kinv = pow(self.k, (-j) % self.m, self.n)
        return ((-kinv * i) % self.n, (-j) % self.m)
    def e(self):
        return (0, 0)
    def pw(self, g, n):
        r = self.e()
        if n < 0:
            g, n = self.inv(g), -n
        for _ in range(n):
            r = self.mul(r, g)
        return r
    def order(self, g):
        r, n = g, 1
        while r != self.e():
            r = self.mul(r, g); n += 1
        return n
    def elements(self):
        return [(i, j) for i in range(self.n) for j in range(self.m)]
    def abelianisation(self):
        """Return (list of commutators, quotient order) by brute force: |G/[G,G]|."""
        els = self.elements()
        comms = set()
        for g in els:
            for h in els:
                comms.add(self.mul(self.mul(g, h), self.mul(self.inv(g), self.inv(h))))
        # subgroup generated by commutators
        sub = set([self.e()])
        frontier = set(comms)
        while frontier:
            new = set()
            for g in frontier:
                for h in list(sub) + list(comms):
                    for p in (self.mul(g, h), self.mul(h, g)):
                        if p not in sub:
                            new.add(p)
            sub |= frontier
            frontier = new - sub
        return sub


def word_images(G, imgs, word):
    r = G.e()
    for name, e in word:
        r = G.mul(r, G.pw(imgs[name], e))
    return r
